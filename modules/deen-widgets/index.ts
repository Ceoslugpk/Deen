import { requireNativeModule } from 'expo';
export type DeenWidgetsNative = {
  publish(json: string): Promise<boolean>;
  refresh(): Promise<boolean>;
  read(): Promise<string | null>;
  clear(): Promise<boolean>;
  tasbihCommand?: (json: string) => Promise<string>;
  tasbihRead?: () => Promise<string | null>;
  consumeDestination?: () => Promise<string | null>;
  addListener?: (event: string, listener: () => void) => { remove(): void };
  startActivity(name: string, time: string, nextAt: number, place: string, method: string): Promise<boolean>;
  stopActivity(): Promise<boolean>;
};
const native = requireNativeModule<DeenWidgetsNative>('DeenWidgetBridge');
export const publishSnapshotJson = (json: string) => native.publish(json);
export const refreshWidgets = () => native.refresh();
export const readSnapshotJson = () => native.read();
export const clearSnapshot = () => native.clear();
export const supportsTasbihCommands = () => typeof native.tasbihCommand === 'function' && typeof native.tasbihRead === 'function';
export const readNativeTasbihJson = async (): Promise<string | null> => native.tasbihRead ? native.tasbihRead() : null;
export const commandTasbihJson = async (json: string): Promise<string | null> => native.tasbihCommand ? native.tasbihCommand(json) : null;
export const consumeWidgetDestination = async (): Promise<string | null> => native.consumeDestination ? native.consumeDestination() : null;
export const subscribeWidgetDestination = (listener: () => void): (() => void) => {
  const subscription = native.addListener?.('onWidgetDestination', listener);
  return () => subscription?.remove();
};
export const startActivity = (name: string, time: string, nextAt: number, place: string, method: string) => native.startActivity(name, time, nextAt, place, method);
export const stopActivity = () => native.stopActivity();
export type WidgetModule = {
  publishSnapshotJson: typeof publishSnapshotJson;
  refreshWidgets: typeof refreshWidgets;
  readSnapshotJson: typeof readSnapshotJson;
  clearSnapshot: typeof clearSnapshot;
  supportsTasbihCommands: typeof supportsTasbihCommands;
  commandTasbihJson: typeof commandTasbihJson;
  readNativeTasbihJson: typeof readNativeTasbihJson;
  consumeWidgetDestination: typeof consumeWidgetDestination;
  subscribeWidgetDestination: typeof subscribeWidgetDestination;
  startActivity: typeof startActivity;
  stopActivity: typeof stopActivity;
};
export type { WidgetSnapshot } from '../../src/services/widgetSnapshot';
