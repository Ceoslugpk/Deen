// Latin script with the full Azerbaijani alphabet — ə, ı, ö, ü, ş, ç, ğ — all
// of which DM Sans carries, so this language ships without a font of its own.
//
// The register is the one Azerbaijani Muslims pray in, drawn from the Alikhan
// Musayev edition the reader is given (tr_az_alikhan_musayev), whose word
// choice was checked against the other five Azerbaijani editions on the
// Islamic Data API before it was picked: God is Allah and never Tanrı, the
// prayer is namaz, the fast is oruc, the purification washing is dəstəmaz and
// the full one is qüsl, alms is zəkat, the pilgrimage is həcc, paradise is
// cənnət and the Fire is cəhənnəm. Words the edition keeps in their Arabic
// transliteration — Alhamdulillah, Subhanallah, Bismillah, Tawaf, Sa'i,
// Ka'bah — are kept here too rather than calqued.
//
// Unlike Vietnamese, the five prayer times are localised rather than left in
// Arabic: Sübh, Günəş, Zöhr, Əsr, Məğrib and İşa are what Azerbaijani
// prayer-time pages print, and the call to prayer is azan.
//
// Surah names follow the convention the other Latin-script languages in this
// app use — the Arabic name carried into the local script with its article
// assimilated — so they read Əl-Fatihə, Ən-Nisa and Ət-Tovbə rather than by
// meaning. The source is quran.az. See src/content/surahNames.ts.

