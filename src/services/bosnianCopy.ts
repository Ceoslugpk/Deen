// Latin script with the five Bosnian letters — č, ć, ž, š, đ (and their
// capitals Č, Ć, Ž, Š, Đ) — all of which DM Sans already carries, so this
// language ships without a font of its own. The twelve Arabic
// transliteration marks the font lacks (ʾ ʿ ḍ ḥ ṣ ṭ ẓ and friends) are
// avoided throughout: where English uses a macron or a dot below, the
// Bosnian rendering uses the plain letter the way Bosnian books print it.
//
// The register is the one Bosnian Muslims pray in, drawn from the Besim
// Korkut edition the reader is given (tr_bs_besim_korkut), whose word choice
// was checked against the other nine Bosnian editions on the Islamic Data
// API before it was picked: God is Allah and never Bog, the prayer is namaz,
// the fast is post, the lesser washing is abdest and the full one is gusul,
// alms is zekat, the pilgrimage is hadž, the mosque is džamija, paradise is
// džennet and the Fire is džehennem. Words the edition keeps in their Arabic
// form — Kur'an, dova, zikr, tefsir, tedžvid, džuz, hizb, sehur, iftar —
// stay in that form here too, because that is how Bosnian Muslims say them.
//
// Where the madhabs differ — the minimum and maximum of hayd, whether the
// Quran may be recited in it, the nisab threshold — the app describes the
// difference rather than settling it, and says so on the screen.
//
