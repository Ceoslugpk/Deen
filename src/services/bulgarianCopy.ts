// Cyrillic, in the register Bulgarian Muslims actually pray in, drawn from the
// Tzvetan Theophanov edition the reader is given (tr_bg_tzvetan_theophanov) —
// the only one of the three Bulgarian editions that is written in Bulgarian
// rather than transliterated. That edition's own word choice was checked
// first: God is Аллах (347 times across 707 sampled verses, never Бог), the
// Lord is Господ (130), the Messenger is Пратеник, the prophet is пророк and
// the mosque is джамия. The ayah is аят and the surah is сура, as the edition
// prints them.
//
// The practical vocabulary is the one the Bulgarian Islamic sources use — the
// Grand Mufti's office, the Bulgarian fiqh references and the Bulgarian
// Wikipedia article on the prayer: намаз for the ritual prayer (not the
// generic молитва), абдест for the lesser washing and гусул for the full one,
// зекят for the alms, садака for voluntary charity, дуа for supplication and
// зикр for remembrance, тефсир for commentary, ихрам, таваф and сай for the
// pilgrimage rites, хайз and нифас and истихада for the states a woman is in.
// The fast is пост, as the edition has it, rather than the Turkish oruç. The
// two Eids are named the way Bulgarian Muslims name them: Рамазан байрям and
// Курбан байрям. The five prayers are Фаджр, Зухр, Аср, Магриб and Иша.
//
// Where the madhabs differ — the minimum and maximum of hayd, whether the
// Quran may be recited in it, the nisab threshold — the app describes the
// difference rather than settling it, and says so on the screen.
//
// No new font ships with this language: not one face in assets/fonts covers
// Cyrillic, and Russian, Kazakh and Cyrillic Uzbek already render through the
// system fallback. Bulgarian follows the same path rather than diverging.
//
// Keys are the English strings, so any untranslated key falls back to
// English at the call site.


