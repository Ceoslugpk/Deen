export function prayerName(code: string | boolean, name: string): string {
    const table = tableFor(code);
    if (!table) return name;
    return PRAYER_TABLES[table][name] ?? name;
  }

  /**
   * Which copy table a language reads from.
   *
   * `null` means English: the screens were written in it, so the source text
   * is already the right answer and there is nothing to look up.
   */
  function tableFor(code: string | boolean): 'ar' | 'ur' | 'tr' | 'fa' | 'id' | 'hi' | 'ml' | null {
    if (typeof code === 'boolean') return code ? 'ar' : null;
    if (code === 'ar') return 'ar';
    if (code === 'ur') return 'ur';
    if (code === 'tr') return 'tr';
    if (code === 'fa') return 'fa';
    if (code === 'id') return 'id';
    if (code === 'hi') return 'hi';
    if (code === 'ml') return 'ml';
    return null;
  }

  /**
   * Translate one string.
   *
   * The first argument is the language code. A boolean is still accepted,
   * because much of the app was written as tx(rtl, ...) before there was a
   * third language to choose between: `true` means Arabic, as it always did.
   *
   * A string with no entry in the chosen language reads as it does in
   * English. An unfinished language is therefore never a screen of blanks —
   * it is a screen that is partly Urdu and partly English until the copy is
   * finished, which is why a new language can be shipped before it is done.
   */
  export function tx(code: string | boolean, text: string): string {
    const table = tableFor(code);
    if (table === 'ar') return AR[text] ?? text;
    if (table === 'ur') return UR[text] ?? text;
    if (table === 'tr') return TR[text] ?? text;
    if (table === 'fa') return FA[text] ?? text;
    if (table === 'id') return ID[text] ?? text;
    if (table === 'hi') return HI[text] ?? text;
    if (table === 'ml') return ML[text] ?? text;
    return text;
  }

/**
 * Translate a sentence that has numbers in it.
 *
 * T(`Starts in ${plan.daysLeft} days`) can never find an entry, because the
 * text it looks up is built at run time and reads "Starts in 97 days". The
 * empty string is the only key that would catch every number, and it is not
 * a key worth having.
 *
 * tf(rtl, 'Starts in {n} days', { n: plan.daysLeft }) keeps the key fixed,
 * so it can be looked up — and because it is looked up as a whole sentence,
 * the Arabic can put the number where Arabic puts it.
 */
export function tf(
  code: string | boolean,
  text: string,
  values: Record<string, string | number>,
): string {
  const out = tx(code, text);
  return out.replace(/\{(\w+)\}/g, (_m, k) => String(values[k] ?? ''));
}

/**
 * Prayer times arrive from the API as 12-hour clock strings such as "5:42 PM".
 *
 * ص and م are how *Arabic* writes the morning and the evening, and Urdu uses
 * the same two marks. They are not a property of "not English", which is what
 * this function used to test: Turkish and Indonesian are written in Latin
 * script and do not use them at all, so both were being handed "5:42 م".
 *
 * Persian is kept in the list only because that is how it has shipped; it is
 * arguable, since Persian more often writes ق.ظ and ب.ظ. Left alone rather
 * than changed here, because Persian is not what this fix is about.
 */
export function clockTime(code: string | boolean, time: string): string {
  const table = tableFor(code);
  if (table !== 'ar' && table !== 'ur' && table !== 'fa') return time;
  return time.replace(/\s*(AM|PM)\s*$/i, (_match, half: string) =>
    half.toUpperCase() === 'AM' ? ' ص' : ' م',
  );
}

/** Arabic nouns change form with the number in front of them: after three to
    ten the plural is read, after eleven and above the singular returns. */
export function arNoun(n: number, one: string, two: string, few: string, many: string): string {
  const m = Math.abs(Math.trunc(n)) % 100;
  if (m === 1) return one;
  if (m === 2) return two;
  if (m >= 3 && m <= 10) return few;
  return many;
}
