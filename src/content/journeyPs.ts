/**
 * The Umrah and Hajj journey in Pashto.
 *
 * Keyed by the step id, which is the same in every language, so a step that has
 * not been written here yet reads in English rather than showing nothing.
 *
 * Reached through a language code, never through an `rtl` flag. Pashto is
 * written right-to-left, so the boolean that once chose between Arabic and
 * English could not have told these two apart either.
 *
 * The wording follows the vocabulary an Afghan and Pashtun pilgrim actually
 * uses: احرام, میقات, طواف, سعي, دوره (the circuit), تلبیه, ګردۍ (the pebble),
 * جمره (the pillar), عرفه, منا, مزدلفه, هدي (the sacrificial animal), طواف
 * الافاضه, د تشریق ورځې. Where the schools of law differ — on what breaks
 * ihram, on whether the sa'i of Hajj comes before or after Tawaf al-Ifadah —
 * the text says so and sends the reader to someone qualified, instead of
 * quietly picking one ruling and presenting it as the only one.
 *
 * The short lines are the same strings the rest of the interface uses, so the
 * wording a person reads on the journey screen is the wording they meet
 * everywhere else.
 *
 * The Prophet ﷺ is never named without the blessing.
 */

