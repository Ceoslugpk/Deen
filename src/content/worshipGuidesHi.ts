/**
 * The worship guides in Hindi.
 *
 * The English guides in `worshipGuides.ts` stay the source of truth: they carry
 * the ids, the reference links and the order. This file holds only the Hindi
 * wording, so a guide that has not been written here yet simply reads in
 * English rather than showing an empty screen.
 *
 * Register note. Hindi Muslim writing keeps the Arabic term wherever the term
 * is itself part of what a person says or does, so वुज़ू stays वुज़ू rather
 * than becoming a descriptive phrase, and रुकू, सज्दा, तकबीर, तशह्हुद and
 * सलाम all appear as themselves. This is not laziness: a Hindi speaker who
 * prays says these words, and rendering them into Sanskrit-derived equivalents
 * would move the text away from the thing it describes — नमाज़ is not
 * प्रार्थना, and रोज़ा is not व्रत.
 *
 * Where a step names something that differs between the schools, the text says
 * so rather than picking one. Where it names a ruling, it names it as
 * something to confirm with a scholar, which is how the English puts it.
 *
 * The Prophet is never a bare name: नबी ﷺ, throughout.
 *
 * Spellings follow `hindiCopy.ts` — the नुक़्ता-bearing क़, ख़, ग़, ज़, फ़
 * are kept, because a reader who says these words daily notices their absence.
 */

