/**
 * The citation forms used in the guide references: "Qur'an 5:6",
 * "Sahih al-Bukhari 164".
 *
 * Only the container word is Hindi — क़ुरआन and the सहीह spelling Hindi
 * editions use — the citation itself is left alone, because a reader looking up
 * "Sahih al-Bukhari 164" needs the number unchanged and does not need the
 * transliteration worked out twice.
 */
export function hindiReference(label: string): string {
  return label
    .replace('Qur’an', 'क़ुरआन')
    .replace('Sahih al-Bukhari', 'सहीह अल-बुख़ारी')
    .replace('Sahih Muslim', 'सहीह मुस्लिम');
}
