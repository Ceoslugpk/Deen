/**
 * Reference labels in Pashto.
 *
 * The numbers are left as they are: Pashto is written in Arabic numerals
 * throughout this app, so a reference reads "قرآن 5:6" and not some other
 * digits. Only the words before the number change.
 */
export function pashtoReference(label: string): string {
  return label
    .replace('Qur’an', 'قرآن')
    .replace('Sahih al-Bukhari', 'صحیح البخاري')
    .replace('Sahih Muslim', 'صحیح مسلم');
}
