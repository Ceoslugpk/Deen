/** The citation forms used in the guide references: "Qur’an 5:6", "Sahih al-Bukhari 164". */
export function russianReference(label: string): string {
  return label
    .replace('Qur’an', 'Коран')
    .replace('Sahih al-Bukhari', 'Сахих аль-Бухари')
    .replace('Sahih Muslim', 'Сахих Муслим');
}
