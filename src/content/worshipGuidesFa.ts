/** The citation forms used in the guide references: "Qur’an 5:6", "Sahih al-Bukhari 164". */
export function persianReference(label: string): string {
  return label
    .replace('Qur’an', 'قرآن')
    .replace('Sahih al-Bukhari', 'صحیح بخاری')
    .replace('Sahih Muslim', 'صحیح مسلم');
}
