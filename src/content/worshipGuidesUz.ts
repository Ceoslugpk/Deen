/**
 * Reference labels in Uzbek.
 *
 * The numbers are left as they are: Uzbek is written in Arabic numerals
 * throughout this app, so a reference reads “Қуръон 5:6” and not some other
 * digits. Only the words before the number change.
 */
export function uzbekReference(label: string): string {
  return label
    .replace('Qur’an', 'Қуръон')
    .replace('Sahih al-Bukhari', 'Саҳиҳ ал-Бухорий')
    .replace('Sahih Muslim', 'Саҳиҳ Муслим');
}
