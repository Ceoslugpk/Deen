/** Reference labels in Arabic, so the citations read in the same language. */
export function arabicReference(label: string): string {
  return label
    .replace('Qur’an', 'القرآن')
    .replace('Sahih al-Bukhari', 'صحيح البخاري')
    .replace('Sahih Muslim', 'صحيح مسلم');
}
