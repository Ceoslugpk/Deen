/**
 * The worship guides in Malayalam.
 *
 * The English guides in `worshipGuides.ts` stay the source of truth: they carry
 * the ids, the reference links and the order. This file holds only the Malayalam
 * wording, so a guide that has not been written here yet simply reads in
 * English rather than showing an empty screen.
 *
 * Register note. Malayalam Muslim writing keeps the Arabic term wherever the
 * term is itself part of what a person says or does, so വുദു stays വുദു rather
 * than becoming a descriptive phrase, and റുകൂഅ്, സുജൂദ്, തക്ബീർ, തശഹ്ഹുദ് and
 * സലാം all appear as themselves. This is not laziness: a Malayali who prays
 * says these words, and rendering them into Sanskrit-derived equivalents would
 * move the text away from the thing it describes — നിസ്കാരം is not പ്രാർത്ഥന,
 * and നോമ്പ് is not വ്രതം.
 *
 * The vocabulary around them is Kerala's: the minor ablution is വുദു, the
 * major one is ഗുസ്ൽ, the prayer unit is റക്അത്ത്, the pre-dawn meal is അത്താഴം
 * and the breaking of the fast is നോമ്പുതുറ. The two festivals are the
 * പെരുന്നാളുകൾ — ചെറിയ പെരുന്നാൾ and വലിയ പെരുന്നാൾ — because that is what
 * they are called, and not by their Arabic names.
 *
 * Where a step names something that differs between the schools, the text says
 * so rather than picking one. Where it names a ruling, it names it as
 * something to confirm with a scholar, which is how the English puts it.
 *
 * The Prophet is never a bare name: നബി ﷺ, throughout.
 */

