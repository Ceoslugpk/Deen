/**
 * Citation labels keep their numbers and change only the book's name, so a
 * reference still resolves to the place a reader can look it up. The hadith
 * collections are named as Malayalam names them — see `hadithSourceLabel`.
 */
export function malayalamReference(label: string): string {
  return label
    .replace(/Qur[’']an/g, 'ഖുർആൻ')
    .replace(/Sahih al-Bukhari/g, 'സ്വഹീഹുൽ ബുഖാരി')
    .replace(/Sahih Muslim/g, 'സ്വഹീഹു മുസ്‌ലിം');
}
