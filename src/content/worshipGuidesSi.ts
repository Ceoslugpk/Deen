/**
 * Reference labels in Sinhala.
 *
 * The numbers are left as they are: Sinhala is written in Arabic numerals
 * throughout this app, so a reference reads "කුර්ආනය 5:6" and not some other
 * digits. Only the words before the number change.
 */
export function sinhalaReference(label: string): string {
  return label
    .replace('Qur’an', 'කුර්ආනය')
    .replace('Sahih al-Bukhari', 'සහීහ් අල්-බුඛාරි')
    .replace('Sahih Muslim', 'සහීහ් මුස්ලිම්');
}
