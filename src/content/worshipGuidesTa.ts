/**
 * Reference labels in Tamil.
 *
 * The numbers are left as they are: Tamil is written in Arabic numerals
 * throughout this app, so a reference reads “குர்ஆன் 5:6” and not some other
 * digits. Only the words before the number change.
 */
export function tamilReference(label: string): string {
  return label
    .replace('Qur’an', 'குர்ஆன்')
    .replace('Sahih al-Bukhari', 'ஸஹீஹ் அல்புகாரி')
    .replace('Sahih Muslim', 'ஸஹீஹ் முஸ்லிம்');
}
