/**
 * The 114 surah names, in every language the app reads.
 *
 * The Quran API answers with two names for each surah: `name_simple`, a
 * transliteration into Latin script ("Al-Baqarah"), and `name_arabic`
 * ("البقرة"). Those are the only two it has. Every other screen in the app
 * had been translated into nine languages, but a surah was still named in
 * English with the Arabic beside it — the one thing a reader looks at most.
 *
 * So the names are held here instead, one per language, and `surahName()`
 * hands out the right one. A language with no table falls back to the
 * English transliteration, exactly as it did before, so nothing regresses.
 *
 * These were not translated from English. Each language's list was taken
 * from the Wikipedia articles for the surahs in that language — the titles
 * readers of that language actually use — via the Arabic Wikipedia's
 * language links, which is the most complete hub for the set. Article
 * prefixes and suffixes were stripped so the name can sit beside a number
 * without reading "Surah Al-Fatihah 1" or "Bakara Suresi 2".
 *
 * That gives the transliterated name in each language, which is what the
 * app was already showing in English. It is deliberately not the *meaning*
 * of the name — Quran.com's translated_name gives "Корова" in Russian and
 * "La vache" in French, but gives transliterations for Malayalam and
 * Turkish, so it is not one kind of thing across languages. A uniform
 * transliteration replaces the English one cleanly; a mixed set would not.
 *
 * Sources: ar.wikipedia.org language links, cross-checked against
 * api.quran.com/api/v4/chapters. All 114 present for all ten languages.
 */

export type SurahNameLanguage = 'en' | 'ar' | 'ur' | 'fa' | 'id' | 'hi' | 'ml' | 'tr' | 'ru' | 'fr' | 'bn' | 'ms' | 'ta' | 'uz' | 'zh';

