/* ==================== Lookup ==================== */

const TABLES: Record<SurahNameLanguage, Record<number, string>> = {
  en: SURAH_NAMES_EN,
  ar: SURAH_NAMES_AR,
  ur: SURAH_NAMES_UR,
  fa: SURAH_NAMES_FA,
  id: SURAH_NAMES_ID,
  hi: SURAH_NAMES_HI,
  ml: SURAH_NAMES_ML,
  tr: SURAH_NAMES_TR,
  ru: SURAH_NAMES_RU,
  fr: SURAH_NAMES_FR,
  bn: SURAH_NAMES_BN,
};

/**
 * The language `surahName()` answers in when it is not told one.
 *
 * The functions that build surah labels are plain data functions with no
 * language threaded through them, so the code is held here the way
 * `hadithService` holds its own — set once when the app language changes,
 * read everywhere after.
 */
let currentLanguage: SurahNameLanguage = 'en';

export function setSurahNameLanguage(code: string): void {
  if (code in TABLES) currentLanguage = code as SurahNameLanguage;
}

export function getSurahNameLanguage(): SurahNameLanguage {
  return currentLanguage;
}

/**
 * The name of one surah in the given language, or in the current one.
 *
 * A surah outside 1-114, or a language with no entry, falls back to the
 * English transliteration rather than to nothing — the caller is building
 * a label and a blank label is worse than an English one.
 */
export function surahName(surahId: number, lang?: string): string {
  const table = TABLES[(lang && lang in TABLES ? lang : currentLanguage) as SurahNameLanguage];
  return table[surahId] ?? SURAH_NAMES_EN[surahId] ?? `Surah ${surahId}`;
}

/** All 114 for a language, as an array indexed from 1 — for pickers and lists. */
export function surahNames(lang?: string): string[] {
  const table = TABLES[(lang && lang in TABLES ? lang : currentLanguage) as SurahNameLanguage];
  const out: string[] = [];
  for (let n = 1; n <= 114; n += 1) out.push(table[n] ?? SURAH_NAMES_EN[n] ?? `Surah ${n}`);
  return out;
}
