/**
 * Reference labels in Bulgarian.
 *
 * The numbers are left as they are: Bulgarian is written in Arabic numerals
 * throughout this app, so a reference reads "Коран 5:6" and not some other
 * digits. Only the words before the number change.
 */
export function bulgarianReference(label: string): string {
  return label
    .replace('Qur’an', 'Коран')
    .replace('Sahih al-Bukhari', 'Сахих ал-Бухари')
    .replace('Sahih Muslim', 'Сахих Мюслим');
}
